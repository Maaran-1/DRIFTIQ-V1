@router.get("/notes/{slug}", response_class=HTMLResponse)
async def public_note(slug: str, session: AsyncSession = Depends(db.get_session)):
    row = (
        await session.execute(
            select(models.Note, models.Lecture)
            .join(models.Lecture, models.Lecture.id == models.Note.lecture_id)
            .where(models.Note.slug == slug, models.Note.status == "published")
        )
    ).first()
    if row is None:
        return HTMLResponse(
            _PAGE.format(
                title="Note not found — DRIFTIQ",
                meta="",
                body="<h1>Note not found</h1><p>This note does not exist or has not been published.</p>",
            ),
            status_code=404,
        )
    note, lecture = row
    date = lecture.created_at.strftime("%d %b %Y") if lecture.created_at else ""
    meta_bits = [b for b in [html.escape(lecture.subject or ""), date] if b]
    return HTMLResponse(
        _PAGE.format(
            title=f"{html.escape(lecture.subject or 'Lecture')} — DRIFTIQ Notes",
            meta=" · ".join(meta_bits),
            body=md_to_html(note.markdown),
        )
    )
