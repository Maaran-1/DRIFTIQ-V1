import html
import re

from fastapi import APIRouter, Depends
from fastapi.responses import HTMLResponse
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

import db
import models

router = APIRouter(tags=["public"])


def md_to_html(md: str) -> str:
    """Tiny markdown renderer for the note format extract.py emits
    (#/##/### headings, - lists, **bold**, `code`)."""
    def inline(s: str) -> str:
        s = html.escape(s)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
        return s

    out: list[str] = []
    in_list = False

    def close():
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    for raw in (md or "").split("\n"):
        line = raw.rstrip()
        if not line:
            close()
            continue
        if line.startswith("### "):
            close(); out.append(f"<h3>{inline(line[4:])}</h3>")
        elif line.startswith("## "):
            close(); out.append(f"<h2>{inline(line[3:])}</h2>")
        elif line.startswith("# "):
            close(); out.append(f"<h1>{inline(line[2:])}</h1>")
        elif line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{inline(line[2:])}</li>")
        else:
            close(); out.append(f"<p>{inline(line)}</p>")
    close()
    return "\n".join(out)


